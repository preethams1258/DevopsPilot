from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether
from xml.sax.saxutils import escape


def p(value) -> str:
    return escape(str(value if value is not None else "—")).replace("\n", "<br/>")


def build_incident_pdf(incident: dict) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=42, leftMargin=42, topMargin=42, bottomMargin=42)
    styles = getSampleStyleSheet()
    story = [Paragraph("DevOpsPilot AI — Incident Report", styles["Title"]), Spacer(1, 8), Paragraph("Evidence-backed incident investigation and remediation record", styles["Italic"]), Spacer(1, 14)]
    rows = [
        ["Incident ID", p(incident["id"])], ["Title", p(incident["title"])],
        ["Severity", p(incident["severity"])], ["Status", p(incident["status"])],
        ["Detected", p(incident.get("created_at"))], ["Last updated", p(incident.get("updated_at"))],
        ["Description", p(incident.get("description"))], ["Probable root cause", p(incident.get("root_cause") or "Not established")],
        ["Confidence", p(incident.get("confidence"))],
    ]
    table = Table(rows, colWidths=[112, 358])
    table.setStyle(TableStyle([("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#edf1f7")), ("GRID", (0, 0), (-1, -1), .4, colors.HexColor("#ccd3df")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("PADDING", (0, 0), (-1, -1), 8)]))
    story.extend([table, Spacer(1, 18), Paragraph("Investigation evidence", styles["Heading2"])])
    for item in incident.get("evidence", []):
        story.append(Paragraph(f"<b>{p(item['source'])}</b>: {p(item['summary'])}", styles["BodyText"]))
        story.append(Spacer(1, 6))
    story.append(Paragraph("Remediation and human approval", styles["Heading2"]))
    for plan in incident.get("plans", []):
        block = [Paragraph(f"<b>{p(plan['action_type'])} to {p(plan['target'])}</b> ({p(plan['risk'])} risk; {p(plan['status'])})", styles["BodyText"]), Paragraph(p(plan["reason"]), styles["BodyText"])]
        approval = plan.get("approval")
        if approval:
            block.append(Paragraph(f"Approval: {p(approval['decision'])} by {p(approval['reviewer'])} at {p(approval['created_at'])}. {p(approval['comment'])}", styles["BodyText"]))
        else:
            block.append(Paragraph("Approval: no human decision recorded.", styles["BodyText"]))
        execution = plan.get("execution")
        if execution:
            block.append(Paragraph(f"Execution: {p(execution['status'])} at {p(execution['executed_at'])}. Result: {p(execution['result'])}", styles["BodyText"]))
        story.extend([KeepTogether(block), Spacer(1, 9)])
    story.append(Paragraph("Incident timeline", styles["Heading2"]))
    for event in incident.get("timeline", []):
        story.append(Paragraph(f"<b>{p(event['created_at'])} · {p(event['type'])}</b>: {p(event['message'])}", styles["BodyText"]))
        story.append(Spacer(1, 5))
    story.extend([Spacer(1, 16), Paragraph("Report generated by DevOpsPilot AI. Confirm findings against source telemetry before operational use.", styles["Italic"])])
    doc.build(story)
    return buffer.getvalue()
